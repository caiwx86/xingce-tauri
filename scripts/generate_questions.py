by_cat: dict[str, list[tuple[str, str, str, list[str], str]]] = {}
seen_candidate_stems: set[str] = set()
for cat, stem, correct, distractors, explanation in candidates:
    if stem in used_stems or stem in seen_candidate_stems:
        continue
    seen_candidate_stems.add(stem)
    by_cat.setdefault(cat, []).append((stem, correct, distractors, explanation))

for cat in ["言语理解", "数量关系", "判断推理", "资料分析", "常识判断"]:
    need = TARGET - counts[cat]
    added = 0
    for stem, correct, distractors, explanation in by_cat.get(cat, []):
        if added >= need:
            break
        correct = str(correct)
        opts = [correct]
        for d in distractors:
            d = str(d)
            if d not in opts:
                opts.append(d)
            if len(opts) == 4:
                break
        if len(opts) != 4:
            continue
        rng.shuffle(opts)
        answer = opts.index(correct)
        questions.append(
            {
                "id": next_id,
                "category": cat,
                "stem": stem,
                "options": opts,
                "answer": answer,
                "explanation": explanation,
            }
        )
        used_stems.add(stem)
        next_id += 1
        counts[cat] += 1
        added += 1
    print(f"{cat}: existing {counts[cat] - added}, added {added}, total {counts[cat]}, candidates {len(by_cat.get(cat, []))}")
    if counts[cat] != TARGET:
        raise SystemExit(f"{cat} 只有 {counts[cat]} 题，未达到 {TARGET}；请补充候选")

