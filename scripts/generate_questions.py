def cand(cat: str, stem: str, correct: str, distractors: list[str], explanation: str) -> None:
    candidates.append((cat, stem, correct, distractors, explanation))


def fmt(v: float, dec: int = 0, suffix: str = "") -> str:
    if dec == 0:
        return f"{int(round(v))}{suffix}"
    return f"{v:.{dec}f}{suffix}"


def add_num(
    cat: str,
    stem: str,
    answer: float,
    explanation: str,
    *,
    dec: int = 0,
    suffix: str = "",
    deltas: tuple[float, ...] = (1, 2, -1, 3, -2),
) -> None:
    correct = fmt(answer, dec, suffix)
    ds: list[str] = []
    for d in deltas:
        v = answer + d
        if v <= 0:
            continue
        s = fmt(v, dec, suffix)
        if s != correct and s not in ds:
            ds.append(s)
    k = 1
    while len(ds) < 3:
        s = fmt(answer + k, dec, suffix)
        if s != correct and s not in ds:
            ds.append(s)
        k += 1
    cand(cat, stem, correct, ds[:3], explanation)


